/*
 * Generates docs/reference/*.md from the self-describing metadata that every
 * mtrader layer returns for {info:'help'} and from the function libraries'
 * `functions` tables. Run with `npm run docs` after changing any option,
 * property or expression function so the reference never drifts from code.
 */

import fs from 'fs';
import os from 'os';
import path from 'path';
import _ from 'underscore';
import config from '../src/config.js';
import Mtrader from '../src/mtrader.js';
config('runInBand', true);
config('offline', true);
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'mtrader-docs-'));
config('cache_dir', path.join(tmp, 'cache'));
config('lib_dir', path.join(tmp, 'lib'));
// enable a throwaway simulation so broker and replicate have something to describe
config('broker.simulation.enabled', true);
config('broker.simulation.simulation', 'docs');

const outDir = path.resolve(import.meta.dirname, '../docs/reference');

const commands = ['fetch', 'quote', 'collect', 'optimize', 'bestsignals', 'strategize', 'broker', 'replicate'];

const libraries = [
    ['common-functions', "Common functions have no restrictions on what expressions they can be used in."],
    ['lookback-functions', "Lookback functions may read data in the past to determine the current value. They are evaluated by quote for a single security."],
    ['indicator-functions', "Indicator functions must be prefixed by an interval and a dot (such as `day.ATR(14)`) and take numbers as parameters."],
    ['rolling-functions', "Rolling functions read values of previous rows across the whole portfolio and are available in collect (and the layers above it)."],
    ['quoting-functions', "Quoting functions are available in collect columns and compare or adjust securities across the portfolio."]
];

main().catch(err => {
    console.error(err);
    process.exitCode = 1;
});

async function main() {
    fs.mkdirSync(outDir, {recursive: true});
    const mtrader = new Mtrader();
    const written = [];
    try {
        for (const cmd of commands) {
            const help = await mtrader[cmd]({info: 'help'}).catch(err => {
                console.warn(`Could not read help for ${cmd}: ${err.message}`);
                return [];
            });
            if (_.isEmpty(help)) continue;
            write(`${cmd}.md`, commandDoc(cmd, help));
            written.push(cmd);
        }
    } finally {
        await mtrader.close();
    }
    write('functions.md', await functionsDoc(libraries));
    write('README.md', indexDoc(written));
}

function write(name, content) {
    fs.writeFileSync(path.join(outDir, name), content);
    console.log("Wrote", path.relative(process.cwd(), path.join(outDir, name)));
}

function header(title) {
    return `# ${title}\n\n<!-- Generated by scripts/generate-reference.js; do not edit by hand. -->\n\n`;
}

function indexDoc(written) {
    return header("Reference") +
        "Generated from each layer's `{info:'help'}` metadata. See " +
        "[architecture](../../ARCHITECTURE.md) for how the layers fit together.\n\n" +
        written.map(cmd => `- [${cmd}](${cmd}.md)`).join('\n') +
        "\n- [Expression functions](functions.md)\n";
}

function commandDoc(cmd, help) {
    // datasources and brokers each contribute an entry; merge entries sharing a name
    const entries = _.values(_.groupBy(help, 'name')).map(group => ({
        name: group[0].name,
        usage: group[0].usage,
        description: _.uniq(_.compact(_.pluck(group, 'description'))),
        properties: _.uniq(_.flatten(_.compact(_.pluck(group, 'properties')))),
        options: Object.assign({}, ...group.map(g => g.options || {}).reverse())
    }));
    return header(cmd) + entries.map(entry => [
        entries.length > 1 ? `## ${entry.name}\n` : '',
        entry.usage ? '```\n' + entry.usage + '\n```\n' : '',
        entry.description.join('\n\n') + '\n',
        _.isEmpty(entry.options) ? '' : '### Options\n\n| Option | Description | Values |\n|---|---|---|\n' +
            _.map(entry.options, (opt, name) => `| \`${name}\` | ${cell(opt.description || opt.usage)} | ${cell(values(opt.values))} |`).join('\n') + '\n',
        _.isEmpty(entry.properties) ? '' : '### Properties\n\n' +
            entry.properties.map(p => '`' + p + '`').join(', ') + '\n'
    ].filter(Boolean).join('\n')).join('\n');
}

async function functionsDoc(libraries) {
    const modules = await Promise.all(libraries.map(([name]) => import(`../src/${name}.js`)));
    return header("Expression functions") +
        "See [expressions](../expressions.md) for syntax, fields and operators.\n\n" +
        libraries.map(([name, intro], i) => {
            const functions = modules[i].default.functions;
            return `## ${name}\n\n${intro}\n\n| Function | Description |\n|---|---|\n` +
                _.keys(functions).sort().map(fname => {
                    const fn = functions[fname];
                    return `| \`${fname}(${args(fn)})\` | ${cell(fn.description)} |`;
                }).join('\n') + '\n';
        }).join('\n');
}

function args(fn) {
    if (_.isString(fn.args)) return fn.args;
    const source = fn.toString();
    const m = source.match(/^[^(]*\(\s*opt\w*\s*,\s*([^)]*)\)/) || source.match(/^[^(]*\(([^)]*)\)/);
    return m ? m[1].trim() : '';
}

function values(vals) {
    if (!vals || !vals.length) return '';
    const list = _.uniq(_.flatten([vals])).map(String);
    return list.length > 12 ? list.slice(0, 12).join(', ') + ', …' : list.join(', ');
}

function cell(text) {
    return (text || '').toString().replace(/\|/g, '\\|').replace(/\s*\n\s*/g, ' ').trim();
}
